    @pytest.mark.parametrize("label", [lbl for _, lbl in ALL_EXAMPLES])
    def test_preview_file_nonempty(self, label):
        path = os.path.join(PREVIEWS_DIR, f"{label}.html")
        size = os.path.getsize(path)
        assert size > 5000, f"{label}: only {size} bytes (too small)"

    def test_write_preview_to_temp_file(self, tmp_path):
        # Test the write_preview function.
        full_path = os.path.join(
            os.path.dirname(__file__), "..",
            "examples/06_tell_your_story.orn"
        )
        with open(full_path) as f:
            src = f.read()
        engine = Engine()
        result = engine.run(src)
        out = tmp_path / "test.html"
        write_preview(result.graph, str(out), artifacts=result.artifacts)
        assert out.exists()
        content = out.read_text()
        assert "<!DOCTYPE html>" in content


