# HTML validity
# ---------------------------------------------------------------------------


class _HTMLValidator(html.parser.HTMLParser):
    def __init__(self):
        super().__init__()
        self.tag_stack = []
        self.errors = []

    def handle_starttag(self, tag, attrs):
        if tag not in ("meta", "link", "br", "hr", "img", "input"):
            self.tag_stack.append(tag)

    def handle_endtag(self, tag):
        if not self.tag_stack:
            self.errors.append(f"unexpected </{tag}>")
            return
        if self.tag_stack[-1] != tag:
            self.errors.append(f"mismatched: expected </{self.tag_stack[-1]}> got </{tag}>")
        else:
            self.tag_stack.pop()


def _validate_html(html_str):
    v = _HTMLValidator()
    v.feed(html_str)
    return v.errors


class TestHTMLValidity:
    @pytest.mark.parametrize("src_path,label", ALL_EXAMPLES)
    def test_preview_is_valid_html(self, src_path, label):
        result = _load_and_run(src_path)
        html_str = generate_preview(result.graph, artifacts=result.artifacts)
        errors = _validate_html(html_str)
        assert not errors, f"{label}: HTML errors: {errors[:3]}"

    @pytest.mark.parametrize("src_path,label", ALL_EXAMPLES)
    def test_preview_starts_with_doctype(self, src_path, label):
        result = _load_and_run(src_path)
        html_str = generate_preview(result.graph, artifacts=result.artifacts)
        assert html_str.startswith("<!DOCTYPE html>")

    @pytest.mark.parametrize("src_path,label", ALL_EXAMPLES)
    def test_preview_has_html_root(self, src_path, label):
        result = _load_and_run(src_path)
        html_str = generate_preview(result.graph, artifacts=result.artifacts)
        assert "<html" in html_str
        assert "</html>" in html_str


