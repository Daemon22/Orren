class TestVisualMeaningfulness:
    @pytest.mark.parametrize("src_path,label", ALL_EXAMPLES)
    def test_preservation_scores_present(self, src_path, label):
        """Each realization target's preservation score should appear
        somewhere in the preview."""
        result = _load_and_run(src_path)
        html_str = generate_preview(result.graph, artifacts=result.artifacts)
        for art in result.artifacts:
            score_str = f"{art.preservation_score:.2f}"
            assert score_str in html_str, (
                f"{label}: preservation score {score_str} for {art.target_name} not in preview"
            )

    @pytest.mark.parametrize("src_path,label", ALL_EXAMPLES)
    def test_target_names_present(self, src_path, label):
        result = _load_and_run(src_path)
        html_str = generate_preview(result.graph, artifacts=result.artifacts)
        for art in result.artifacts:
            assert art.target_name in html_str, (
                f"{label}: target name {art.target_name} not in preview"
            )

    @pytest.mark.parametrize("src_path,label", ALL_EXAMPLES)
    def test_node_count_present(self, src_path, label):
        result = _load_and_run(src_path)
        html_str = generate_preview(result.graph, artifacts=result.artifacts)
        # The node count should appear as a stat somewhere.
        assert str(result.sir_node_count) in html_str or str(len(result.graph.nodes)) in html_str

    @pytest.mark.parametrize("src_path,label", ALL_EXAMPLES)
    def test_css_uses_design_tokens(self, src_path, label):
        """The CSS should reference design token CSS variables."""
        result = _load_and_run(src_path)
        html_str = generate_preview(result.graph, artifacts=result.artifacts)
        assert "var(--" in html_str, f"{label}: CSS doesn't use design tokens"
        assert "var(--bg)" in html_str or "var(--accent)" in html_str

    @pytest.mark.parametrize("src_path,label", ALL_EXAMPLES)
    def test_layout_strategy_applied(self, src_path, label):
        """The design tokens' layout_strategy should be reflected in the HTML."""
        result = _load_and_run(src_path)
        tokens = extract_design_tokens(result.graph)
        html_str = generate_preview(result.graph, artifacts=result.artifacts)
        # Each layout strategy produces distinct CSS class patterns.
        strategy_markers = {
            "document": ["document-page", "doc-header", "doc-body"],
            "dashboard": ["layout-dashboard", "app-header", "canvas-panel"],
            "app": ["layout-app", "app-canvas", "app-panels"],
            "atmospheric": ["atmospheric-scene", "atmospheric-header", "atmosphere-grid"],
            "schematic": ["layout-schematic", "schematic-canvas", "sch-component"],
        }
        markers = strategy_markers.get(tokens.layout_strategy, [])
        if markers:
            found_any = any(m in html_str for m in markers)
            assert found_any, (
                f"{label}: layout strategy {tokens.layout_strategy} markers not found"
            )


