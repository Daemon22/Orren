class TestStructuralCompleteness:
    @pytest.mark.parametrize("src_path,label", ALL_EXAMPLES)
    def test_contains_app_name(self, src_path, label):
        result = _load_and_run(src_path)
        html_str = generate_preview(result.graph, artifacts=result.artifacts)
        assert result.graph.root.name in html_str

    @pytest.mark.parametrize("src_path,label", ALL_EXAMPLES)
    def test_contains_purpose_text(self, src_path, label):
        result = _load_and_run(src_path)
        html_str = generate_preview(result.graph, artifacts=result.artifacts)
        # Find the purpose from the root expression dimension.
        purpose = ""
        for entry in result.graph.root.get_dimension(__import__("orren_engine").Dimension.EXPRESSION):
            if isinstance(entry, dict) and entry.get("key") == "purpose":
                purpose = str(entry.get("value", ""))
                break
        if purpose:
            # At least the first few words of the purpose should appear.
            first_words = purpose[:30]
            assert first_words in html_str, f"{label}: purpose text not in preview"

    @pytest.mark.parametrize("src_path,label", ALL_EXAMPLES)
    def test_contains_entity_names(self, src_path, label):
        result = _load_and_run(src_path)
        html_str = generate_preview(result.graph, artifacts=result.artifacts)
        # At least 3 entity names should appear in the preview.
        found = 0
        for node in result.graph.nodes[:10]:
            if node.name in html_str:
                found += 1
        assert found >= 3, f"{label}: only {found} entity names found in preview"

    @pytest.mark.parametrize("src_path,label", ALL_EXAMPLES)
    def test_contains_orren_version(self, src_path, label):
        result = _load_and_run(src_path)
        html_str = generate_preview(result.graph, artifacts=result.artifacts)
        from orren_engine import __version__
        assert __version__ in html_str


