class TestPreviewStability:
    def test_same_input_same_output(self):
        full_path = os.path.join(
            os.path.dirname(__file__), "..",
            "examples/06_tell_your_story.orn"
        )
        with open(full_path) as f:
            src = f.read()
        engine = Engine()
        result = engine.run(src)
        html1 = generate_preview(result.graph, artifacts=result.artifacts)
        # Re-run from scratch.
        engine2 = Engine()
        result2 = engine2.run(src)
        html2 = generate_preview(result2.graph, artifacts=result2.artifacts)
        assert html1 == html2
