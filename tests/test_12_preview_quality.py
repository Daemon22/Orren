"""Preview quality tests — layout-agnostic.

Validates that the HTML previews generated by orren_engine.preview are:
  - Syntactically valid HTML (parseable by html.parser)
  - Self-contained (inline CSS + JS, no external dependencies)
  - Structurally complete (header, content, footer)
  - Visually meaningful (entities rendered, vibes applied, scores shown)
  - Displayable in any modern browser

These tests are LAYOUT-AGNOSTIC: they check that the *content* is present
(preservation scores, equilibrium rules, entity names) without asserting
specific CSS class names, because different layout strategies (document,
dashboard, app, atmospheric, schematic) use different markup.

Run: pytest tests/test_12_preview_quality.py -v
"""
