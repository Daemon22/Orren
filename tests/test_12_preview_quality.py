class TestEquilibriumContent:
    @pytest.mark.parametrize("src_path,label", ALL_EXAMPLES)
    def test_equilibrium_rules_mentioned(self, src_path, label):
        """If the graph has equilibrium rules, their names should appear
        somewhere in the preview (in the equilibrium panel or as
        badges on entity cards)."""
        result = _load_and_run(src_path)
        if not result.graph.equilibrium_rules:
            return
        html_str = generate_preview(result.graph, artifacts=result.artifacts)
        # At least half of the rule names should be in the preview.
        found = sum(1 for r in result.graph.equilibrium_rules if r.name in html_str)
        total = len(result.graph.equilibrium_rules)
        assert found >= total * 0.5, (
            f"{label}: only {found}/{total} equilibrium rule names in preview"
        )
